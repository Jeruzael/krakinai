export function projectStillCamera(composition:CameraComposition|undefined):{text:string;omittedIds:string[];error?:string}{
 if(!composition)return{text:'',omittedIds:[]};
 const error=validateCameraComposition(composition);if(error)return{text:'',omittedIds:[],error};
 const parts=composition.techniqueIds.filter(id=>Object.hasOwn(STILL_CAMERA_TEXT,id)).map(id=>STILL_CAMERA_TEXT[id]);
 const p=composition.parameters;
 if(p?.focalLengthMm!==undefined)parts.push(`Focal length: ${p.focalLengthMm} mm.`);
 if(p?.apertureFNumber!==undefined)parts.push(`Aperture: f/${p.apertureFNumber}.`);
 return{text:parts.join('\n'),omittedIds:composition.techniqueIds.filter(id=>!Object.hasOwn(STILL_CAMERA_TEXT,id))};
}
